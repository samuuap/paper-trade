"""Baseline schema + TimescaleDB hypertables.

The baseline revision builds the tables straight from the SQLAlchemy metadata.
That guarantees revision 1 can never drift from `app/db/models.py`, which is
what you want for an initial schema; every change after this one is a normal
hand-written or autogenerated revision. (Trade-off: offline `--sql` mode is not
supported for this revision.)

Revision ID: 0001
Revises:
"""

from __future__ import annotations

import sqlalchemy as sa
from alembic import op

from app.db.base import Base
from app.db.models import HYPERTABLES

revision = "0001"
down_revision = None
branch_labels = None
depends_on = None


def _timescale_available(bind) -> bool:
    return bool(
        bind.execute(
            sa.text("SELECT 1 FROM pg_available_extensions WHERE name = 'timescaledb'")
        ).scalar()
    )


def upgrade() -> None:
    bind = op.get_bind()
    has_timescale = _timescale_available(bind)
    if has_timescale:
        op.execute("CREATE EXTENSION IF NOT EXISTS timescaledb CASCADE")

    Base.metadata.create_all(bind=bind)

    if not has_timescale:
        # Plain Postgres still works; we just lose the chunking and the
        # time_bucket helpers. Recorded so /health can report it.
        return

    for table, time_column in HYPERTABLES.items():
        op.execute(
            sa.text(
                f"SELECT create_hypertable('{table}', '{time_column}', "
                "if_not_exists => TRUE, migrate_data => TRUE, "
                "chunk_time_interval => INTERVAL '7 days')"
            )
        )

    # Quote history is high-volume and only interesting recently; compress the
    # older chunks. Bars and equity curves stay uncompressed for fast reads.
    op.execute(
        "ALTER TABLE market_quotes SET ("
        "  timescaledb.compress,"
        "  timescaledb.compress_segmentby = 'symbol'"
        ")"
    )
    op.execute("SELECT add_compression_policy('market_quotes', INTERVAL '7 days')")


def downgrade() -> None:
    bind = op.get_bind()
    Base.metadata.drop_all(bind=bind)
